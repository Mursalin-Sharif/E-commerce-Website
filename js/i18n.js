function getLang() {
  return localStorage.getItem("lang") === "bn" ? "bn" : "en";
}

function setLang(lang) {
  localStorage.setItem("lang", lang === "bn" ? "bn" : "en");
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: getLang() } }));
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N.en[key] || key);
}

function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang === "bn" ? "bn" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function categoryLabel(cat) {
  return getLang() === "bn" ? cat.nameBn : cat.name;
}

function productLabel(product) {
  return getLang() === "bn" ? product.nameBn : product.name;
}
